"""Machine-readable MCP tool contract. Data only: no MCP SDK import.

``contract.json`` is generated by ``python -m skeleton.mcp.contract`` and committed.
"""

import json
from enum import StrEnum
from typing import Annotated, Final

from pydantic import BaseModel, ConfigDict, Field

from skeleton.ingest.models import FileHistory, Import, Symbol
from skeleton.signals.models import AnalyzerStatus, Finding

TOOL_GET_SNAPSHOT: Final = "get_snapshot"
TOOL_LIST_FINDINGS: Final = "list_findings"
TOOL_GET_FILE_FACTS: Final = "get_file_facts"
TOOL_READ_LINES: Final = "read_lines"

TOOL_NAMES: Final[frozenset[str]] = frozenset(
    {TOOL_GET_SNAPSHOT, TOOL_LIST_FINDINGS, TOOL_GET_FILE_FACTS, TOOL_READ_LINES}
)

DEFAULT_LIMIT: Final = 20
MAX_LIMIT: Final = 100
READ_LINES_MAX: Final = 200


class ErrorCode(StrEnum):
    """R4 citation codes that can occur without a quote, plus tool-level codes."""

    MALFORMED = "malformed"
    PATH_UNSAFE = "path_unsafe"
    SYMLINK = "symlink"
    FILE_NOT_FOUND = "file_not_found"
    RANGE_INVALID = "range_invalid"
    RANGE_OUT_OF_BOUNDS = "range_out_of_bounds"
    TOOL_NOT_ALLOWED = "tool_not_allowed"
    INVALID_ARGUMENT = "invalid_argument"


ERROR_DESCRIPTIONS: Final[dict[ErrorCode, str]] = {
    ErrorCode.MALFORMED: "The request or citation is malformed.",
    ErrorCode.PATH_UNSAFE: "The path is absolute, escapes the snapshot, or is otherwise unsafe.",
    ErrorCode.SYMLINK: "The path is, or passes through, a symlink.",
    ErrorCode.FILE_NOT_FOUND: "No such file in the snapshot.",
    ErrorCode.RANGE_INVALID: "The line range is invalid (for example start after end, or below 1).",
    ErrorCode.RANGE_OUT_OF_BOUNDS: "The line range extends past the end of the file.",
    ErrorCode.TOOL_NOT_ALLOWED: "The tool is not in this persona's allowed tools.",
    ErrorCode.INVALID_ARGUMENT: "An argument is missing, has the wrong type, or is out of range.",
}

METRIC_DESCRIPTIONS: Final[dict[str, str]] = {
    "commit_count": (
        "Number of commits since the current path was created. Renames are not followed "
        "and merge commits contribute no files, so a renamed file's history starts at the rename."
    ),
    "author_count": (
        "Number of distinct authors of commits since the current path was created."
    ),
    "days_since_modified": (
        "Days since the file was last changed by a commit on the current path. "
        "Renames are not followed."
    ),
    "age_days": (
        "Days since this line last changed (git blame). Editing a TODO's wording resets its age."
    ),
    "todo_count_in_file": "Number of TODO-style markers in the file.",
}

ANALYZER_DESCRIPTIONS: Final[dict[str, str]] = {
    "churn": "Files with many commits since the current path was created.",
    "staleness": "Files not changed for a long time.",
    "todo_age": "TODO markers, aged by days since this line last changed.",
}


class _Model(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")


class ToolError(_Model):
    code: ErrorCode
    message: str


class ErrorResponse(_Model):
    error: ToolError
    snapshot_id: str


# ---- inputs ----


class GetSnapshotInput(_Model):
    pass


class ListFindingsInput(_Model):
    analyzer: str | None = None
    file: str | None = None
    min_severity: Annotated[float, Field(ge=0.0, le=1.0)] | None = None
    limit: int | None = Field(
        default=None,
        description=f"Default {DEFAULT_LIMIT}; values above {MAX_LIMIT} are clamped.",
    )


class GetFileFactsInput(_Model):
    file: str


class ReadLinesInput(_Model):
    file: str
    line_start: int
    line_end: int


# ---- outputs ----


class GetSnapshotOutput(_Model):
    snapshot_id: str
    source: str
    licence: str
    history_available: bool
    file_count: int
    analyzers: list[AnalyzerStatus]


class FindingWithId(Finding):
    id: str


class ListFindingsOutput(_Model):
    snapshot_id: str
    findings: list[FindingWithId] = Field(
        description="Ordered by severity descending, then file, then line_start."
    )
    total_matching: int
    limit_applied: int
    clamped: bool
    analyzers: list[AnalyzerStatus] = Field(
        description="Always present. A skipped or failed analyzer is reported here, "
        "so an empty findings list is not evidence of a clean repository."
    )


class GetFileFactsOutput(_Model):
    snapshot_id: str
    file: str
    line_count: int
    symbols: list[Symbol]
    imports: list[Import]
    history: FileHistory | None
    history_available: bool


class ReadLinesOutput(_Model):
    snapshot_id: str
    file: str
    lines: list[str]
    line_start: int
    returned_line_end: int
    truncated: bool = Field(
        description=f"True when the range exceeded {READ_LINES_MAX} lines and was cut."
    )


INPUT_MODELS: Final[dict[str, type[BaseModel]]] = {
    TOOL_GET_SNAPSHOT: GetSnapshotInput,
    TOOL_LIST_FINDINGS: ListFindingsInput,
    TOOL_GET_FILE_FACTS: GetFileFactsInput,
    TOOL_READ_LINES: ReadLinesInput,
}

OUTPUT_MODELS: Final[dict[str, type[BaseModel]]] = {
    TOOL_GET_SNAPSHOT: GetSnapshotOutput,
    TOOL_LIST_FINDINGS: ListFindingsOutput,
    TOOL_GET_FILE_FACTS: GetFileFactsOutput,
    TOOL_READ_LINES: ReadLinesOutput,
}

TOOL_DESCRIPTIONS: Final[dict[str, str]] = {
    TOOL_GET_SNAPSHOT: "Snapshot ID, source, licence, history availability, file count and analyzer statuses.",
    TOOL_LIST_FINDINGS: (
        "List findings filtered by analyzer, file and min_severity. Ordered by severity "
        "descending, then file, then line_start. Reports clamping and analyzer skipped/failed status."
    ),
    TOOL_GET_FILE_FACTS: "Line count, symbols, imports and history metadata for one file.",
    TOOL_READ_LINES: (
        f"Normalised lines line_start..line_end of one file, at most {READ_LINES_MAX} lines."
    ),
}


def build_contract() -> dict[str, object]:
    return {
        "tools": {
            name: {
                "description": TOOL_DESCRIPTIONS[name],
                "input_schema": INPUT_MODELS[name].model_json_schema(),
                "output_schema": OUTPUT_MODELS[name].model_json_schema(),
            }
            for name in sorted(TOOL_NAMES)
        },
        "error_response_schema": ErrorResponse.model_json_schema(),
        "error_codes": {c.value: ERROR_DESCRIPTIONS[c] for c in ErrorCode},
        "limits": {
            "default_limit": DEFAULT_LIMIT,
            "max_limit": MAX_LIMIT,
            "read_lines_max": READ_LINES_MAX,
        },
        "metrics": dict(METRIC_DESCRIPTIONS),
        "analyzers": dict(ANALYZER_DESCRIPTIONS),
    }


def render_contract_json() -> str:
    return json.dumps(build_contract(), indent=2, sort_keys=True) + "\n"


if __name__ == "__main__":
    import sys

    sys.stdout.write(render_contract_json())
